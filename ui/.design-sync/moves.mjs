// Generates the Moves and Phone line of every design-system card (A-19 P6) from
// `moves.json`, one small table, instead of writing it 100 times by hand.
//
//   node .design-sync/moves.mjs          writes the block at the top of each preview
//                                        and the whole table to MOVES.md
//   node .design-sync/moves.mjs --check  exits 1 if either is out of date
//
// A card with no row in the table takes the defaults. A card with no preview
// file is still in MOVES.md, which the resync reads for the floor cards.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const BEGIN = "// moves:begin (generated by .design-sync/moves.mjs; edit moves.json)";
const END = "// moves:end";

export function linesFor(name, table) {
  const row = table.cards[name] ?? {};
  return {
    moves: row.moves ?? table.defaults.moves,
    phone: row.phone ?? table.defaults.phone,
  };
}

export function blockFor(name, table) {
  const { moves, phone } = linesFor(name, table);
  return `${BEGIN}\n// Moves: ${moves}\n// Phone: ${phone}\n${END}\n`;
}

/** The preview's source with its block written (replacing an older one, else at the top). */
export function withBlock(source, name, table) {
  const block = blockFor(name, table);
  const start = source.indexOf("// moves:begin");
  if (start === -1) return `${block}${source}`;
  const end = source.indexOf(END, start);
  return `${source.slice(0, start)}${block}${source.slice(end + END.length + 1)}`;
}

export function tableMarkdown(names, table) {
  const rows = names.map((name) => {
    const { moves, phone } = linesFor(name, table);
    return `| ${name} | ${moves} | ${phone} |`;
  });
  return [
    "# Moves and Phone, per card",
    "",
    "Generated by `.design-sync/moves.mjs` from `moves.json`. Do not edit here.",
    "",
    "| Card | Moves | Phone |",
    "| --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const table = JSON.parse(readFileSync(join(HERE, "moves.json"), "utf8"));
  const config = JSON.parse(readFileSync(join(HERE, "config.json"), "utf8"));
  const names = Object.keys(config.componentSrcMap);
  const stale = [];
  const put = (path, text) => {
    const was = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (was === text) return;
    if (check) stale.push(path);
    else writeFileSync(path, text);
  };
  for (const name of names) {
    const path = join(HERE, "previews", `${name}.tsx`);
    if (existsSync(path)) put(path, withBlock(readFileSync(path, "utf8"), name, table));
  }
  put(join(HERE, "MOVES.md"), tableMarkdown(names, table));
  if (check && stale.length) {
    console.error(`Out of date, run node .design-sync/moves.mjs:\n${stale.join("\n")}`);
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
